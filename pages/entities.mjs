// Names in other languages, generated by tools/i18n-names.mjs from the game's i18n-<code>-content chunks.
export const L10N = JSON.parse(readFileSync(new URL('../data/i18n-names.json', import.meta.url), 'utf8'));
const L10N_EXTRA = { boss: ['title', 'Title'], dog: ['breed', 'Breed'] };

function localNames(kind, id) {
  const e = L10N.names[kind]?.[id];
  if (!e) return '';
  const [field, label] = L10N_EXTRA[kind] ?? [];
  const langs = L10N.languages.filter((l) => l.tag !== 'en');
  const cell = (l, s) => (l.dir === 'rtl' ? `<bdi>${s}</bdi>` : s);
  const rows = langs.map((l) => [l.endonym === l.englishName ? l.endonym : `${cell(l, l.endonym)} · ${l.englishName}`, `\`${l.tag}\``, cell(l, e.name[l.tag]), ...(field ? [cell(l, e[field][l.tag])] : [])]);
  const english = L10N.alwaysEnglish.includes(`content.${kind}.${id}.name`);
  const src = english
    ? `**Verified**: the game always shows this name in English, whatever the language. <small>[${L10N.build.boot}: \`\` new Set([\`content.${kind}.${id}.name\`]) \`\`]</small>${field ? ` The ${label.toLowerCase()} is translated.` : ''}`
    : `**Verified**: the name the game shows when another language is selected in Settings, from its translation files. <small>[${e.cite.chunk}: \`${e.cite.quote}\`]</small>`;
  return `## Names in other languages\n\n${src} See [Languages](/controls#languages).\n\n<details class="raw"><summary>Show names in ${langs.length} languages</summary>\n\n${table(['Language', 'Code', 'Name', ...(field ? [label] : [])], rows)}\n</details>\n\n`;
}

// Inserts each page's localized-name section above its raw data block (or at the end).
function withLocalNames(kind, pages) {
  for (const p of pages) {
    const s = localNames(kind, p.path.split('/').pop());
    const at = p.body.indexOf('## Data\n');
    p.body = at < 0 ? `${p.body.trimEnd()}\n\n${s}` : p.body.slice(0, at) + s + p.body.slice(at);
    if (s) p.sources.push(`Names in other languages from the game's ${L10N.languages.length - 1} per-language content files (\`i18n-*-content\`) of \`${L10N.build.main}\` (\`data/i18n-names.json\`)`);
  }
  return pages;
}

// Flatten nested behaviour parameters into key/value rows.
function flatRows(obj, prefix = '') {
  const rows = [];
  for (const [k, v] of Object.entries(obj ?? {})) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v) && Object.keys(v).length) rows.push(...flatRows(v, key));
    else rows.push([`\`${key}\``, Array.isArray(v) ? json(v) : v && typeof v === 'object' ? '(present)' : fmt(v)]);
  }
  return rows;
}

// An enemy found in many biomes would make its catalogue row very tall; past two, the list folds behind a count.
function biomeCell(list) {
  const items = list.map((b) => `${link('biome', b.biome)} (T${b.tier})`).join(', ');
  if (list.length <= 2) return items;
  const tiers = [...new Set(list.map((b) => b.tier))].sort((x, y) => x - y);
  const range = tiers.length > 1 ? `T${tiers[0]}–T${tiers.at(-1)}` : `T${tiers[0]}`;
  return `<details class="cell-more"><summary>${list.length} biomes, ${range}</summary>${items}</details>`;
}

// The intro answers "what do I do with it": the bold one-action lead of the page's first tip, when it has one.
// The in-game flavour text moves to the infobox, so the lead does not spend the first lines on a quote.
function keyTip(dir, id) {
  let md = '';
  try { md = readFileSync(new URL(`../data/prose/${dir}/${id}.md`, import.meta.url), 'utf8'); } catch { return ''; }
  const m = md.match(/^## Tips\n+- \*\*(.+?)\*\*/m);
  return m ? ` **Key tip:** ${m[1]}` : '';
}

